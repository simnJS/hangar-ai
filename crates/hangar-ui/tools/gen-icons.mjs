#!/usr/bin/env node
// Writes crates/hangar-ui/src/icon/data.rs from src/components/Icon.tsx: the
// glyph drawings of the web app's icon set, as the `Icon` enum and the SVG
// elements of each. Reading the TSX rather than copying the paths by hand is
// what keeps the native icons the web app's own, and lets the drawings be
// refreshed when an icon is added there.
//
//   node crates/hangar-ui/tools/gen-icons.mjs
//
// The TSX holds each glyph as JSX made only of <rect>, <path> and <circle>
// elements (and fragments around them), so a regular expression is enough to
// lift them out; the script fails loudly on a glyph with anything else in it.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const source = readFileSync(resolve(root, "src/components/Icon.tsx"), "utf8");
const out = resolve(here, "../src/icon/data.rs");

// From `const PATHS = {` to `} as const;`.
const start = source.indexOf("const PATHS = {");
const end = source.indexOf("} as const;");
if (start < 0 || end < 0) throw new Error("the PATHS table was not found in Icon.tsx");
const table = source.slice(start + "const PATHS = {".length, end);

// A key is at the start of a line, two spaces in: `  layout1:`. The JSX of a
// glyph is indented deeper, so it never matches.
const keyAt = /^ {2}([a-zA-Z0-9]+):/gm;
const keys = [...table.matchAll(keyAt)];

const icons = [];
for (let i = 0; i < keys.length; i += 1) {
  const name = keys[i][1];
  const body = table.slice(keys[i].index + keys[i][0].length, keys[i + 1]?.index ?? table.length);
  // Comments between glyphs belong to the next key's chunk; drop them.
  const jsx = body.replace(/\/\/[^\n]*/g, "");
  const elements = [...jsx.matchAll(/<(rect|path|circle)\b([^>]*?)\/>/g)].map(
    (match) => `<${match[1]}${match[2].replace(/\s+/g, " ").replace(/\s$/, "")}/>`,
  );
  // Whatever is left once the known elements and fragments are gone is
  // something this script does not understand.
  const rest = jsx
    .replace(/<(rect|path|circle)\b[^>]*?\/>/g, "")
    .replace(/<\/?>/g, "")
    .replace(/[(),\s]/g, "");
  if (!elements.length || rest) {
    throw new Error(`glyph "${name}" has JSX this script cannot read: ${rest || "(no elements)"}`);
  }
  // `currentColor` is the tint: the renderer replaces the colour of every
  // pixel anyway, so any opaque colour will do.
  icons.push({ name, svg: elements.join("").replaceAll("currentColor", "#000") });
}

const pascal = (name) => name[0].toUpperCase() + name.slice(1);

const lines = [];
lines.push("// Generated by tools/gen-icons.mjs from src/components/Icon.tsx. Do not edit by hand.");
lines.push("");
lines.push("/// Every icon of the web app's set, by the name it had there (`splitRight` is");
lines.push("/// [`Icon::SplitRight`]).");
lines.push("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]");
lines.push("pub enum Icon {");
for (const { name } of icons) lines.push(`    ${pascal(name)},`);
lines.push("}");
lines.push("");
lines.push("impl Icon {");
lines.push("    /// All of them, in the order of the web app's table.");
lines.push(`    pub const ALL: [Icon; ${icons.length}] = [`);
for (const { name } of icons) lines.push(`        Icon::${pascal(name)},`);
lines.push("    ];");
lines.push("");
lines.push("    /// The name the web app knows it by (`\"splitRight\"`), which is what the");
lines.push("    /// settings and the saved layouts store.");
lines.push("    pub const fn name(self) -> &'static str {");
lines.push("        match self {");
for (const { name } of icons) lines.push(`            Icon::${pascal(name)} => "${name}",`);
lines.push("        }");
lines.push("    }");
lines.push("");
lines.push("    /// The elements drawn inside the 16-unit box.");
lines.push("    #[rustfmt::skip]");
lines.push("    pub(super) const fn elements(self) -> &'static str {");
lines.push("        match self {");
for (const { name, svg } of icons) {
  lines.push(`            Icon::${pascal(name)} => r##"${svg}"##,`);
}
lines.push("        }");
lines.push("    }");
lines.push("}");
lines.push("");

writeFileSync(out, lines.join("\n"));
console.log(`${icons.length} icons written to ${out}`);

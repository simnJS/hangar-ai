#!/usr/bin/env node
// Writes crates/hangar-theme/src/data.rs from the TypeScript the Tauri app is
// themed by: the 33 palettes of src/themes.ts, and for each of them every
// token `deriveChromeTokens` gives. Running the real TypeScript rather than
// copying its numbers by hand is what keeps the Rust tables exactly the same
// as the web app's; the crate's own `derive` module is then held to them by a
// test, so the two implementations check each other.
//
//   node crates/hangar-theme/tools/gen-themes.mjs
//
// Needs Node 22.18 or later, which runs TypeScript by stripping its types.
// themes.ts imports "./lib/contrast" without an extension, which Node does
// not resolve, so both files are copied to a scratch directory with `.ts`
// added to that one import. Nothing in the repository is modified but data.rs.

import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const out = resolve(here, "../src/data.rs");

const scratch = mkdtempSync(join(tmpdir(), "hangar-themes-"));
let themes;
let derive;
try {
  mkdirSync(join(scratch, "lib"));
  cpSync(join(root, "src/lib/contrast.ts"), join(scratch, "lib/contrast.ts"));
  const source = readFileSync(join(root, "src/themes.ts"), "utf8").replace(
    'from "./lib/contrast"',
    'from "./lib/contrast.ts"',
  );
  writeFileSync(join(scratch, "themes.ts"), source);
  // The package.json makes Node treat the copies as ES modules.
  writeFileSync(join(scratch, "package.json"), '{"type":"module"}');
  const module = await import(pathToFileURL(join(scratch, "themes.ts")).href);
  themes = module.THEMES;
  derive = module.deriveChromeTokens;
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const ANSI = [
  "black",
  "red",
  "green",
  "yellow",
  "blue",
  "magenta",
  "cyan",
  "white",
  "brightBlack",
  "brightRed",
  "brightGreen",
  "brightYellow",
  "brightBlue",
  "brightMagenta",
  "brightCyan",
  "brightWhite",
];

/** `#rrggbb` as the Rust helper `rgb(0xrrggbb)`. */
function hex(value, where) {
  if (!/^#[0-9a-f]{6}$/i.test(value ?? "")) throw new Error(`${where}: "${value}" is not #rrggbb`);
  return `rgb(0x${value.slice(1).toLowerCase()})`;
}

/** A token's value, `#rrggbb` or `rgba(r, g, b, a)`, as Rust. */
function color(value, where) {
  const rgba = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value ?? "");
  if (rgba) return `rgba(${rgba[1]}, ${rgba[2]}, ${rgba[3]}, ${rgba[4]})`;
  return hex(value, where);
}

const field = (name) => name.replace(/^--/, "").replaceAll("-", "_");

const ids = new Set();
let keys;
const blocks = themes.map((theme) => {
  if (ids.has(theme.id)) throw new Error(`duplicate theme id ${theme.id}`);
  ids.add(theme.id);
  const where = theme.id;
  const x = theme.xterm;
  const tokens = derive(theme);
  const names = Object.keys(tokens);
  keys ??= names;
  if (names.join() !== keys.join()) throw new Error(`${where}: tokens differ from the first theme's`);

  const terminal = [
    `foreground: ${hex(x.foreground, `${where} foreground`)}`,
    `background: ${hex(x.background, `${where} background`)}`,
    `cursor: ${hex(x.cursor, `${where} cursor`)}`,
    `cursor_text: ${hex(x.cursorAccent, `${where} cursorAccent`)}`,
    `selection: ${hex(x.selectionBackground, `${where} selectionBackground`)}`,
    `ansi: [${ANSI.map((slot) => hex(x[slot], `${where} ${slot}`)).join(", ")}]`,
  ].join(",\n            ");

  const colors = names
    .map((name) => `${field(name)}: ${color(tokens[name], `${where} ${name}`)}`)
    .join(",\n            ");

  return `    Theme {
        id: ${JSON.stringify(theme.id)},
        name: ${JSON.stringify(theme.name)},
        appearance: Appearance::${theme.appearance === "dark" ? "Dark" : "Light"},
        terminal: TerminalColors {
            ${terminal},
        },
        colors: Colors {
            ${colors},
        },
    },`;
});

const file = `// Generated by tools/gen-themes.mjs from src/themes.ts: do not edit by hand.
// Change the TypeScript (or the script) and run it again; the \`derive\` test
// fails when this table and the Rust implementation of deriveChromeTokens
// disagree.

use crate::{Appearance, Colors, TerminalColors, Theme, rgb, rgba};

#[rustfmt::skip]
pub(crate) static THEMES: [Theme; ${blocks.length}] = [
${blocks.join("\n")}
];
`;

writeFileSync(out, file);
console.log(`${blocks.length} themes, ${keys.length} tokens each, written to ${out}`);

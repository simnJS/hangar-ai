#!/usr/bin/env bash
# Build and start the test node: sshd on 127.0.0.1:<port>, user `hangar`, key auth.
#   up.sh [--arm64] [--with-claude]
# Port: HANGAR_NODE_TEST_PORT, else the first free one from 2222.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

platform=""
with_claude=0
for a in "$@"; do
  case "$a" in
    --arm64) platform="linux/arm64" ;;
    --with-claude) with_claude=1 ;;
    -h|--help) sed -n '2,4p' "$0"; exit 0 ;;
    *) echo "unknown argument: $a" >&2; exit 2 ;;
  esac
done

command -v docker >/dev/null || { echo "docker not found" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "docker daemon not reachable" >&2; exit 1; }

if [ "$platform" = "linux/arm64" ] && [ "$(uname -m)" != "aarch64" ] && [ "$(uname -m)" != "arm64" ]; then
  if ! docker run --rm --platform linux/arm64 debian:trixie-20251020-slim@sha256:66b37a5078a77098bfc80175fb5eb881a3196809242fd295b25502854e12cbec uname -m 2>/dev/null | grep -q '^aarch64$'; then
    echo "arm64 containers do not run on this machine (install qemu-user-binfmt); skipping." >&2
    exit 0
  fi
fi

mkdir -p "$KEYS_DIR"
chmod 700 "$KEYS_DIR"
if [ ! -f "$KEY" ]; then
  ssh-keygen -q -t ed25519 -N '' -C hangar-node-test -f "$KEY"
fi

docker rm -f "$CONTAINER" >/dev/null 2>&1 || true

tag="hangar-node-test:${platform:+arm64}"
tag="${tag%:}"; [ "$tag" = "hangar-node-test" ] && tag="hangar-node-test:amd64"
build=(docker build -q -t "$tag" --build-arg "WITH_CLAUDE=$with_claude")
[ -n "$platform" ] && build+=(--platform "$platform")
"${build[@]}" "$RIG_DIR" >/dev/null

if [ -n "${HANGAR_NODE_TEST_PORT:-}" ]; then
  port="$HANGAR_NODE_TEST_PORT"
  port_is_free "$port" || { echo "port $port is already in use" >&2; exit 1; }
else
  port=2222
  while ! port_is_free "$port"; do port=$((port + 1)); [ "$port" -lt 2300 ] || { echo "no free port" >&2; exit 1; }; done
fi

run=(docker run -d --name "$CONTAINER" -p "127.0.0.1:$port:22")
[ -n "$platform" ] && run+=(--platform "$platform")
"${run[@]}" "$tag" >/dev/null

docker cp "$KEY.pub" "$CONTAINER:/home/hangar/.ssh/authorized_keys"
docker exec "$CONTAINER" sh -c 'chown hangar:hangar /home/hangar/.ssh/authorized_keys && chmod 600 /home/hangar/.ssh/authorized_keys'

echo "$port" > "$STATE_PORT"
: > "$KNOWN_HOSTS"
cat > "$SSH_CONFIG" <<CFG
# Generated by up.sh (do not edit, not committed).
Host $HOST_ALIAS
  HostName 127.0.0.1
  Port $port
  User hangar
  IdentityFile $KEY
  IdentitiesOnly yes
  UserKnownHostsFile $KNOWN_HOSTS
  StrictHostKeyChecking no
  BatchMode yes
  LogLevel ERROR
CFG

mapfile -t opts < <(rig_ssh_opts)
ok=0
for _ in $(seq 1 120); do
  if ssh "${opts[@]}" -p "$port" hangar@127.0.0.1 true 2>/dev/null; then ok=1; break; fi
  sleep 1
done
if [ "$ok" != 1 ]; then
  echo "sshd did not come up in time; container logs:" >&2
  docker logs "$CONTAINER" >&2 || true
  exit 1
fi

cat <<OUT
Test node up ($(docker exec "$CONTAINER" uname -m)).
  target:  hangar@127.0.0.1 port $port
  ssh:     ssh -i $KEY -p $port -o StrictHostKeyChecking=no -o UserKnownHostsFile=$KNOWN_HOSTS hangar@127.0.0.1
  config:  ssh -F $SSH_CONFIG $HOST_ALIAS
  helper:  $RIG_DIR/ssh.sh <cmd>
OUT
